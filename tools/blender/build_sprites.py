"""Turns the Blender renders into Factorio sprite sheets, graphics/<variant>/entity/sprites.lua,
the icons and the portal thumbnail (all three wagons side by side).

Usage: python tools/blender/build_sprites.py [render_dir] [variant ...]   (default: tools/blender/out, all wagons)
Turret heads are built when named, e.g. howitzer-turret (from <render_dir>/howitzer-turret).
Expects the layout written by render_all.sh: <render_dir>/<variant>/{color,mask,shadow}_NNN.png
"""
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import pack  # noqa: E402

from PIL import Image  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
VARIANTS = ["mg", "flame", "rocket", "twin", "howitzer", "mine"]
# default train colour of each wagon, for the icons (keep in sync with wagon.color in prototypes/<variant>.lua)
COLORS = {
    "mg": (0.35, 0.4, 0.25), "flame": (0.55, 0.3, 0.15), "rocket": (0.3, 0.33, 0.38),
    "twin": (0.3, 0.36, 0.22), "howitzer": (0.4, 0.38, 0.26), "mine": (0.42, 0.4, 0.18),
}
# the wagons on the portal thumbnail
THUMBNAIL = ["mg", "flame", "rocket"]
FRAMES = 128
TURRET_FRAMES = 64


def write_sheet(out, images, origin, name, line_length, lines_per_file=None):
    """Crops all frames to their common bounding box and writes sheet file(s).

    origin: pixel position of the entity position in the (uncropped) frames.
    Returns the metadata table for sprites.lua.
    """
    box = None
    for im in images:
        b = im.getbbox()
        if b:
            box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    w, h = box[2] - box[0], box[3] - box[1]
    count = len(images)
    line_length = min(line_length, count)
    lines_per_file = lines_per_file or math.ceil(count / line_length)
    per_file = line_length * lines_per_file
    files = []
    for f in range(math.ceil(count / per_file)):
        chunk = images[f * per_file:(f + 1) * per_file]
        lines = math.ceil(len(chunk) / line_length)
        sheet = Image.new("RGBA", (w * line_length, h * lines))
        for k, im in enumerate(chunk):
            sheet.paste(im.crop(box), ((k % line_length) * w, (k // line_length) * h))
        fname = f"{name}-{f + 1}.png" if per_file < count else f"{name}.png"
        sheet.save(os.path.join(out, fname), optimize=True)
        files.append(fname)
    cx, cy = (box[0] + box[2]) / 2, (box[1] + box[3]) / 2
    return {
        "files": files, "width": w, "height": h, "line_length": line_length, "lines_per_file": lines_per_file,
        "frame_count": count, "shift": ((cx - origin[0]) / 64, (cy - origin[1]) / 64),
    }


def origin_of(src):
    """Pixel position of the world origin in a (final size) frame, from the render's camera.json."""
    with open(os.path.join(src, "camera.json")) as f:
        cam = json.load(f)
    return (cam["width"] * 64 / 2, (cam["height"] / 2 + cam["shift_y"]) * 64)


def lua(value, indent=""):
    if isinstance(value, dict):
        inner = indent + "  "
        items = ",\n".join(f"{inner}[\"{k}\"] = {lua(v, inner)}" for k, v in value.items())
        return "{\n" + items + "\n" + indent + "}"
    if isinstance(value, (list, tuple)):
        return "{ " + ", ".join(lua(v, indent) for v in value) + " }"
    if isinstance(value, str):
        return f"\"{value}\""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return f"{value:.4f}"
    return str(value)


def fit(img, size):
    img = img.crop(img.getbbox())
    scale = size / max(img.size)
    img = img.resize((max(1, round(img.width * scale)), max(1, round(img.height * scale))), Image.LANCZOS)
    canvas = Image.new("RGBA", (size, size))
    canvas.alpha_composite(img, ((size - img.width) // 2, (size - img.height) // 2))
    return canvas


def build(render_dir, variant):
    src = os.path.join(render_dir, variant)
    out = os.path.join(ROOT, "graphics", variant, "entity")
    icons = os.path.join(ROOT, "graphics", variant, "icons")
    os.makedirs(out, exist_ok=True)
    os.makedirs(icons, exist_ok=True)
    origin = origin_of(src)
    meta = {"wagon": {kind: write_sheet(out, [pack.load(src, kind, i) for i in range(FRAMES)], origin, f"wagon-{kind}", 8, 4)
                      for kind in ("color", "mask", "shadow")}}
    with open(os.path.join(out, "sprites.lua"), "w") as f:
        f.write("-- Generated by tools/blender/build_sprites.py, do not edit.\nreturn " + lua(meta) + "\n")
    # icon: the wagon seen at an angle, in its default colour
    wagon = pack.tinted(pack.load(src, "color", 40), pack.load(src, "mask", 40), COLORS[variant])
    fit(wagon, 64).save(os.path.join(icons, "wagon.png"))
    print("wrote sprites and icon for", variant)
    return wagon


def build_turret(render_dir, variant):
    """Turret head (turret.py): 64 directions, painted in the wagon's colour, since a turret
    takes no train colour. Writes graphics/<wagon>/entity/turret-*.png and turret.lua."""
    wagon_variant = variant[:-len("-turret")]
    src = os.path.join(render_dir, variant)
    out = os.path.join(ROOT, "graphics", wagon_variant, "entity")
    os.makedirs(out, exist_ok=True)
    origin = origin_of(src)
    color = [pack.tinted(pack.load(src, "color", i), pack.load(src, "mask", i), COLORS[wagon_variant])
             for i in range(TURRET_FRAMES)]
    shadow = [pack.load(src, "shadow", i) for i in range(TURRET_FRAMES)]
    meta = {"color": write_sheet(out, color, origin, "turret-color", 8),
            "shadow": write_sheet(out, shadow, origin, "turret-shadow", 8)}
    with open(os.path.join(out, "turret.lua"), "w") as f:
        f.write("-- Generated by tools/blender/build_sprites.py, do not edit.\nreturn " + lua(meta) + "\n")
    print("wrote turret sprites for", wagon_variant)


def thumbnail(wagons):
    """Portal thumbnail: the wagons stacked diagonally, front one last."""
    size = 144
    canvas = Image.new("RGBA", (size, size))
    step = size // (len(wagons) + 2)
    for k, wagon in enumerate(wagons):
        part = fit(wagon, size - step * (len(wagons) - 1))
        canvas.alpha_composite(part, (step * (len(wagons) - 1 - k), step * k))
    canvas.save(os.path.join(ROOT, "thumbnail.png"))


def main(render_dir, variants):
    for v in variants:
        if v.endswith("-turret"):
            build_turret(render_dir, v)
    wagons = {v: build(render_dir, v) for v in variants if not v.endswith("-turret")}
    if all(v in wagons for v in THUMBNAIL):
        thumbnail([wagons[v] for v in THUMBNAIL])
        print("wrote thumbnail")


if __name__ == "__main__":
    args = sys.argv[1:]
    render_dir = args.pop(0) if args and args[0] not in VARIANTS and not args[0].endswith("-turret") else os.path.join(ROOT, "tools", "blender", "out")
    main(render_dir, args or VARIANTS)
