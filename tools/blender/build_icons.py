"""Turns the plate renders (tools/blender/plates.py) into icons and equipment sprites.

Usage: python tools/blender/build_icons.py [render_dir]   (default: tools/blender/out/plates)
Writes graphics/armor/<name>-icon.png (64 px), graphics/armor/<name>-equipment.png
(128 px, drawn at half size over 2x2 grid cells) and graphics/armor/icons.lua, the list
of names that have graphics.
"""
import os
import sys

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "graphics", "armor")


def square(image, margin=0.04):
    """Crops to the visible part, centred on a square canvas with a small margin."""
    box = image.getchannel("A").getbbox()
    part = image.crop(box)
    side = int(max(part.size) * (1 + 2 * margin))
    canvas = Image.new("RGBA", (side, side))
    canvas.alpha_composite(part, ((side - part.width) // 2, (side - part.height) // 2))
    return canvas


def main(render_dir):
    os.makedirs(OUT, exist_ok=True)
    names = []
    for file in sorted(os.listdir(render_dir)):
        if not file.endswith(".png"):
            continue
        name = file[:-4]
        image = square(Image.open(os.path.join(render_dir, file)).convert("RGBA"))
        image.resize((64, 64), Image.LANCZOS).save(os.path.join(OUT, name + "-icon.png"), optimize=True)
        if name != "armor-steel":
            image.resize((128, 128), Image.LANCZOS).save(os.path.join(OUT, name + "-equipment.png"), optimize=True)
        names.append(name)
    with open(os.path.join(OUT, "icons.lua"), "w") as f:
        f.write("-- generated by tools/blender/build_icons.py\nreturn {\n")
        for name in names:
            f.write(f'  ["{name}"] = true,\n')
        f.write("}\n")
    print("wrote", len(names), "icons")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "tools", "blender", "out", "plates"))
